import { expect, test } from '@playwright/test';

test('subscription catalog is protected, responsive and informational without restricting existing access', async ({ page }, info) => {
  await page.goto('/subscription');
  await expect(page).toHaveURL(/\/login$/);
  await page.goto('/register');
  await page.getByLabel('Your name').fill('Subscription Demo Investor');
  await page.getByLabel('Email address').fill('subscription-browser@example.test');
  await page.getByLabel(/^Password/).fill('Subscription browser passphrase');
  await page.getByRole('button', { name: 'Create account' }).click();
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Subscription Plans' }).click();
  await expect(page).toHaveURL(/\/subscription$/);
  const free = page.getByRole('region', { name: 'Free' });
  const pro = page.getByRole('region', { name: 'Pro' });
  await expect(free.getByText('$0', { exact: true })).toBeVisible();
  await expect(free.getByText('Current Plan', { exact: true })).toBeVisible();
  await expect(pro.getByText('No price announced', { exact: true })).toBeVisible();
  await expect(pro.getByText('Not available yet. Pro cannot be purchased.', { exact: true })).toBeVisible();
  await expect(pro.getByRole('button')).toHaveCount(0);
  await expect(pro.getByRole('link')).toHaveCount(0);
  const catalog = await page.request.get('/api/v1/subscription-plans');
  expect(catalog.status()).toBe(200);
  expect((await catalog.json()).data.map((plan: { code: string; priceMonthly: string | null }) => [plan.code, plan.priceMonthly])).toEqual([['free', '0.00'], ['pro', null]]);
  await page.screenshot({ path: info.outputPath('subscription-desktop.png'), fullPage: true, animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))));
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await expect(free).toBeVisible();
  await expect(pro).toBeVisible();
  await expect.poll(() => free.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
  await expect.poll(() => free.evaluate(element => element.getBoundingClientRect().right <= innerWidth)).toBe(true);
  await expect(free.getByText('Current Plan', { exact: true })).toBeInViewport();
  for (const card of [free, pro]) await expect.poll(() => card.evaluate(element => [...element.querySelectorAll('*')].every(child => child.getBoundingClientRect().right <= innerWidth + 1))).toBe(true);
  await page.screenshot({ path: info.outputPath('subscription-mobile.png'), fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'Open navigation' }).click();
  await expect(page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Subscription Plans' })).toBeVisible();
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Portfolios', exact: true }).click();
  await expect(page).toHaveURL(/\/portfolios$/);
  await expect(page.getByRole('heading', { name: 'A home for your investments.' })).toBeVisible();
  for (const endpoint of ['portfolios', 'assets', 'watchlists']) expect((await page.request.get(`/api/v1/${endpoint}`)).status()).toBe(200);
  await page.setViewportSize({ width: 1280, height: 720 });
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await expect(page).toHaveURL(/\/login$/);
  await page.goto('/subscription');
  await expect(page).toHaveURL(/\/login$/);
});
